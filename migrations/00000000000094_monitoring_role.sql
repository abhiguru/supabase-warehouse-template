-- Migration 94: a monitoring login of its own, and no login for supabase_functions_admin
-- (TW-BE-002; docs/CONTAINER_SECURITY.md, "Database passwords").
--
-- Until now the Postgres exporter and the Grafana PostgreSQL datasource signed in as `postgres`
-- with POSTGRES_PASSWORD, the password of every database login. They now use warehouse_monitoring:
-- a member of pg_monitor (statistics views and settings, read only) and nothing else: no
-- superuser, role, database, replication or RLS-bypass right and no grant on any object.
--
-- This migration creates the role without a login and without a password, because a migration must
-- not hold a secret. scripts/configure-db-roles.sql, which setup.sh runs after the migrations and
-- both restore paths run after their replay, gives it LOGIN and its own password
-- (DB_PASSWORD_MONITORING in config/compose.env, generated by scripts/configure.mjs).
--
-- supabase_functions_admin owns the webhook functions (docker/volumes/db/webhooks.sql), which run
-- with its rights without anyone logging in as it. Nothing signs in as it, yet it had the shared
-- password; it becomes NOLOGIN without a password. Its grants and ownerships do not change. The role
-- exists only where the Compose init scripts ran, so the statement is skipped where it is absent.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'warehouse_monitoring') THEN
    CREATE ROLE warehouse_monitoring NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS INHERIT;
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_auth_members m
    JOIN pg_roles granted ON granted.oid = m.roleid
    JOIN pg_roles member ON member.oid = m.member
    WHERE granted.rolname = 'pg_monitor' AND member.rolname = 'warehouse_monitoring'
  ) THEN
    GRANT pg_monitor TO warehouse_monitoring;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'supabase_functions_admin') THEN
    ALTER ROLE supabase_functions_admin WITH NOLOGIN PASSWORD NULL;
  END IF;
END $$;
