#!/usr/bin/env node
// A small fictional facility for the seeded upgrade drill (the seeded-upgrade job of .github/workflows/ci.yml) and for tests/migrations.sh:
// 8 customers, a staff member, 12 items, 300 goods receipts, 200 dispatches, 40 invoices, 3 orders with 4 lines, and 6 photos (3 receipt photos, 3
// dispatch photos) with their rows in grn_images / dispatch_images and storage.objects. Every name and number is invented. The SQL is
// written for supabase_admin (direct inserts; the rules of the RPCs are not in the way) and is the same on every run.
//   node tests/seed/make-seed.mjs [--clash] [--photos DIR] > seed.sql
//   --clash   customers 7 and 8 get names that differ only in capitals and spaces ("Seed Harbour Traders" and " seed  HARBOUR traders"),
//             which migration 117 (unique customers_name_norm_key) refuses to index. The seed loads only into a database without that index.
//   --photos DIR   also writes the six small image files where the Storage service keeps them (DIR/stub/stub/<bucket>/<name>/<version>),
//             so that DIR can be copied into the storage volume of an installation.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { isMain } from '../../scripts/is-main.mjs';

export const COUNTS = { customers: 8, items: 12, grns: 300, dispatches: 200, invoices: 40, orders: 3, orderLines: 4, photos: 6 };

// A 1x1 JPEG; the same bytes for every photo (the catalog lists them by name and version).
const JPEG = Buffer.from('/9j/4AAQSkZJRgABAQEASABIAAD/2wBDAP//////////////////////////////////////////////////////////////////////////////////////wgALCAABAAEBAREA/8QAFBABAAAAAAAAAAAAAAAAAAAAAP/aAAgBAQABPxA=', 'base64');

export function photoList() {
  const rows = [];
  for (let n = 1; n <= 3; n += 1) rows.push({ kind: 'grn', n, bucket: 'grn-images', name: `seed-grn-${n}/photo-${n}.jpg`, version: `00000000-0000-4000-8000-00000000010${n}` });
  for (let n = 1; n <= 3; n += 1) rows.push({ kind: 'dispatch', n, bucket: 'dispatch-images', name: `seed-dispatch-${n}/photo-${n}.jpg`, version: `00000000-0000-4000-8000-00000000020${n}` });
  return rows;
}

export function seedSql({ clash = false } = {}) {
  const photos = photoList();
  const customers = Array.from({ length: COUNTS.customers }, (_, i) => {
    const n = i + 1;
    let name = `Seed Customer ${n}`;
    if (n === 7) name = 'Seed Harbour Traders';
    if (n === 8) name = clash ? ' seed  HARBOUR traders ' : 'Seed Orchard Traders';
    return `  (md5('seed-c${n}')::uuid, '${name}', '98000010${String(n).padStart(2, '0')}', 'Surat')`;
  });
  return `-- Generated by tests/seed/make-seed.mjs${clash ? ' --clash' : ''}. Fictional data; do not edit.
\\set ON_ERROR_STOP on
BEGIN;
INSERT INTO public.customers(id, name, mobile, city) VALUES
${customers.join(',\n')};
INSERT INTO public.items(id, name, packaging)
 SELECT md5('seed-item' || n)::uuid, 'Seed Item ' || n, 'Bag' FROM generate_series(1, ${COUNTS.items}) AS n;
-- ${COUNTS.grns} receipts, each with two lines; the customers take turns.
INSERT INTO public.goodsreceived(id, gr_no, date, customer_id, customer_name, invoiced)
 SELECT md5('seed-g' || n)::uuid, 'SG' || lpad(n::text, 6, '0'), timestamptz '2026-01-01 08:00+00' + (n || ' hours')::interval,
        c.id, c.name, n <= ${COUNTS.invoices}
 FROM generate_series(1, ${COUNTS.grns}) AS n
 JOIN public.customers c ON c.id = md5('seed-c' || ((n - 1) % ${COUNTS.customers} + 1))::uuid;
INSERT INTO public.goodsreceived_trl(id, gr_id, item_id, item_name, packaging, qty, weight, stock)
 SELECT md5('seed-gt' || n || '-' || l)::uuid, md5('seed-g' || n)::uuid, i.id, i.name, 'Bag', 20, 10 + l, CASE WHEN n <= ${COUNTS.dispatches} AND l = 1 THEN 15 ELSE 20 END
 FROM generate_series(1, ${COUNTS.grns}) AS n CROSS JOIN generate_series(1, 2) AS l
 JOIN public.items i ON i.id = md5('seed-item' || ((n + l) % ${COUNTS.items} + 1))::uuid;
-- ${COUNTS.dispatches} dispatches of 5 bags from the first line of the first ${COUNTS.dispatches} receipts.
INSERT INTO public.dispatch(id, disp_no, disp_date, customer_id, customer_name)
 SELECT md5('seed-d' || n)::uuid, 'SD' || lpad(n::text, 6, '0'), g.date + interval '2 days', g.customer_id, g.customer_name
 FROM generate_series(1, ${COUNTS.dispatches}) AS n JOIN public.goodsreceived g ON g.id = md5('seed-g' || n)::uuid;
INSERT INTO public.dispatch_trl(id, gr_id, gr_trl_id, disp_id, disp_qty)
 SELECT md5('seed-dt' || n)::uuid, md5('seed-g' || n)::uuid, md5('seed-gt' || n || '-1')::uuid, md5('seed-d' || n)::uuid, 5
 FROM generate_series(1, ${COUNTS.dispatches}) AS n;
-- ${COUNTS.invoices} invoices, one per receipt of the first ${COUNTS.invoices}, each over the dispatch of that receipt.
INSERT INTO public.invoice(id, inv_fin_year, inv_no, gr_id, gr_no, customer_id, customer_name, inv_date, total)
 SELECT md5('seed-i' || n)::uuid, 2026, n, g.id, g.gr_no, g.customer_id, g.customer_name, g.date + interval '5 days', 100 + n
 FROM generate_series(1, ${COUNTS.invoices}) AS n JOIN public.goodsreceived g ON g.id = md5('seed-g' || n)::uuid;
INSERT INTO public.invoice_trl(id, invoice_id, disp_trl_id)
 SELECT md5('seed-it' || n)::uuid, md5('seed-i' || n)::uuid, md5('seed-dt' || n)::uuid FROM generate_series(1, ${COUNTS.invoices}) AS n;
INSERT INTO public.user_profiles(id, auth_user_id, mobile, name, role, active, enrollment_status)
 VALUES (md5('seed-creator')::uuid, md5('seed-creator-auth')::uuid, '919800009999', 'Seed Staff Member', 'staff', true, 'approved');
-- ${COUNTS.orders} orders and ${COUNTS.orderLines} order lines (the first two orders have one or two lines, the third one).
INSERT INTO public.orders(id, order_no, order_date, requested_dispatch_date, status, priority, customer_id, customer_name, created_by)
 SELECT md5('seed-o' || n)::uuid, 'SO' || lpad(n::text, 4, '0'), timestamptz '2026-02-01 09:00+00', timestamptz '2026-02-05 09:00+00', 'OPEN', 'normal',
        c.id, c.name, md5('seed-creator')::uuid
 FROM generate_series(1, ${COUNTS.orders}) AS n JOIN public.customers c ON c.id = md5('seed-c' || n)::uuid;
INSERT INTO public.order_items(id, order_id, order_no, requested_quantity, grn_items_id, grn_items_item_id, grn_items_item_name, grn_items_package_mark,
                               grn_items_packaging, grn_items_rack, grn_items_weight, grns_id, grns_gr_no, grns_date, grns_customer_id, grns_customer_name,
                               available_stock_at_order, current_stock, item_status, sort_order)
 SELECT md5('seed-oi' || l)::uuid, md5('seed-o' || o)::uuid, 'SO' || lpad(o::text, 4, '0'), 3, t.id, t.item_id, t.item_name, '', 'Bag', '', t.weight,
        g.id, g.gr_no, g.date, g.customer_id, g.customer_name, t.stock, t.stock, 'pending', l
 FROM (VALUES (1, 1, ${COUNTS.customers + 1}), (2, 1, ${COUNTS.customers * 2 + 1}), (3, 2, ${COUNTS.customers + 2}), (4, 3, ${COUNTS.customers + 3})) AS v(l, o, gn)
 JOIN public.goodsreceived g ON g.id = md5('seed-g' || v.gn)::uuid
 JOIN public.goodsreceived_trl t ON t.gr_id = g.id AND t.id = md5('seed-gt' || v.gn || '-2')::uuid
 JOIN public.orders od ON od.id = md5('seed-o' || v.o)::uuid AND od.customer_id = g.customer_id;
-- ${COUNTS.photos} photos: the rows that name them, and the catalog rows of Storage (the files are written by --photos).
${photos.filter(p => p.kind === 'grn').map(p => `INSERT INTO public.grn_images(id, grn_id, image_type, storage_path, original_filename, file_size, mime_type, status)
 VALUES (md5('seed-gi${p.n}')::uuid, md5('seed-g${p.n}')::uuid, 'header', '${p.name}', 'photo-${p.n}.jpg', ${JPEG.length}, 'image/jpeg', 'confirmed');`).join('\n')}
${photos.filter(p => p.kind === 'dispatch').map(p => `INSERT INTO public.dispatch_images(id, dispatch_id, storage_path, original_filename, file_size, mime_type, status)
 VALUES (md5('seed-di${p.n}')::uuid, md5('seed-d${p.n}')::uuid, '${p.name}', 'photo-${p.n}.jpg', ${JPEG.length}, 'image/jpeg', 'confirmed');`).join('\n')}
INSERT INTO storage.objects(id, bucket_id, name, version, metadata) VALUES
${photos.map(p => `  (md5('seed-so${p.kind}${p.n}')::uuid, '${p.bucket}', '${p.name}', '${p.version}', '{"size": ${JPEG.length}, "mimetype": "image/jpeg", "cacheControl": "max-age=3600"}'::jsonb)`).join(',\n')};
COMMIT;
`;
}

export function writePhotos(directory) {
  for (const photo of photoList()) {
    const file = join(directory, 'stub', 'stub', photo.bucket, photo.name, photo.version);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, JPEG);
  }
}

if (isMain(import.meta.url)) {
  const args = process.argv.slice(2);
  const clash = args.includes('--clash');
  const at = args.indexOf('--photos');
  const known = args.filter((arg, i) => arg !== '--clash' && arg !== '--photos' && !(at >= 0 && i === at + 1));
  if (known.length || (at >= 0 && !args[at + 1])) {
    process.stderr.write('Usage: make-seed.mjs [--clash] [--photos DIR] > seed.sql\n');
    process.exit(2);
  }
  if (at >= 0) writePhotos(args[at + 1]);
  process.stdout.write(seedSql({ clash }));
}
